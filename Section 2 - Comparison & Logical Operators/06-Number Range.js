// Number Range 
// Take a number. 
// Check whether the number is between 
// 10 and 100, including both boundaries. 
// Example: 
// Input: 50 
// Output: Number is between 10 and 100 

let num = 50;
if (num<=100 && num>=10){
    console.log(`Number ${num} b/w 10 and 100`);
}
else{
    console.log("No!!");
}
